#ifndef LTC4281_REGS_H_
#define LTC4281_REGS_H_

#include <zephyr/sys/util.h>

/* ---------- Control (0x00-0x01) ---------- */
#define LTC4281_REG_CONTROL_LSB 0x00
#define LTC4281_CTRL_OV_RETRY BIT(0)
#define LTC4281_CTRL_UV_RETRY BIT(1)
#define LTC4281_CTRL_OC_RETRY BIT(2)
#define LTC4281_CTRL_FET_ON BIT(3)
#define LTC4281_CTRL_MASS_WRITE_EN BIT(4)
#define LTC4281_CTRL_ON_ACTIVE_HIGH BIT(5)
#define LTC4281_CTRL_ON_DELAY BIT(6)
#define LTC4281_CTRL_ON_FAULT_MASK BIT(7)

#define LTC4281_REG_CONTROL_MSB 0x01
#define LTC4281_CTRL_VIN_MODE GENMASK(1, 0)
#define LTC4281_CTRL_OV_MODE GENMASK(3, 2)
#define LTC4281_CTRL_UV_MODE GENMASK(5, 4)

/* VIN_MODE values: select the SOURCE/VDD ADC range */
#define LTC4281_VIN_MODE_3V3 0
#define LTC4281_VIN_MODE_5V 1
#define LTC4281_VIN_MODE_12V 2
#define LTC4281_VIN_MODE_24V 3

/* ---------- Logs (0x04-0x05) ---------- */
#define LTC4281_REG_FAULT_LOG 0x04
#define LTC4281_FAULT_OV BIT(0)
#define LTC4281_FAULT_UV BIT(1)
#define LTC4281_FAULT_OC BIT(2)
#define LTC4281_FAULT_POWER_BAD BIT(3)
#define LTC4281_FAULT_ON_CHANGE BIT(4)
#define LTC4281_FAULT_FET_SHORT BIT(5)
#define LTC4281_FAULT_FET_BAD BIT(6)

#define LTC4281_REG_ADC_ALERT_LOG 0x05
#define LTC4281_ADC_ALERT_GPIO_LOW BIT(0)
#define LTC4281_ADC_ALERT_GPIO_HIGH BIT(1)
#define LTC4281_ADC_ALERT_VSOURCE_LOW BIT(2)
#define LTC4281_ADC_ALERT_VSOURCE_HIGH BIT(3)
#define LTC4281_ADC_ALERT_VSENSE_LOW BIT(4)
#define LTC4281_ADC_ALERT_VSENSE_HIGH BIT(5)
#define LTC4281_ADC_ALERT_POWER_LOW BIT(6)
#define LTC4281_ADC_ALERT_POWER_HIGH BIT(7)

/* ---------- Config (0x06-0x07) ---------- */
#define LTC4281_REG_FET_BAD_TIMEOUT 0x06
#define LTC4281_REG_GPIO_CONFIG 0x07
#define LTC4281_GPIO_CONFIG_GPIO1 GENMASK(5, 4)

/* ---------- 8-bit alarm thresholds (0x08-0x0F) ---------- */
#define LTC4281_REG_VGPIO_ALARM_MIN 0x08
#define LTC4281_REG_VGPIO_ALARM_MAX 0x09
#define LTC4281_REG_VSOURCE_ALARM_MIN 0x0A
#define LTC4281_REG_VSOURCE_ALARM_MAX 0x0B
#define LTC4281_REG_VSENSE_ALARM_MIN 0x0C
#define LTC4281_REG_VSENSE_ALARM_MAX 0x0D
#define LTC4281_REG_POWER_ALARM_MIN 0x0E
#define LTC4281_REG_POWER_ALARM_MAX 0x0F

/* ---------- Clock + current limit (0x10-0x11) ---------- */
#define LTC4281_REG_CLOCK_DIVIDER 0x10
#define LTC4281_CLK_DIV GENMASK(4, 0)
#define LTC4281_CLKOUT GENMASK(6, 5)

#define LTC4281_REG_ILIM_ADJUST 0x11
#define LTC4281_ILIM_ADC_16BIT BIT(0) /* verify in datasheet */
#define LTC4281_ILIM_GPIO_MODE BIT(1)
#define LTC4281_ILIM_VSOURCE_SELECT BIT(2) /* 1 = SOURCE, 0 = VDD */
#define LTC4281_ILIM_FOLDBACK_MODE GENMASK(4, 3)
#define LTC4281_ILIM_LIMIT GENMASK(7, 5)

/* ---------- Accumulators (0x12-0x1B) ---------- */
#define LTC4281_REG_ENERGY 0x12
#define LTC4281_ENERGY_LEN 6
#define LTC4281_REG_TIME_COUNTER 0x18
#define LTC4281_TIME_COUNTER_LEN 4

/* ---------- Alert / ADC control / status (0x1C-0x1F) ---------- */
#define LTC4281_REG_ALERT_CONTROL 0x1C
#define LTC4281_ALERT_CTRL_ALERT_OUT BIT(6)

#define LTC4281_REG_ADC_CONTROL 0x1D
#define LTC4281_ADC_CTRL_FAULT_LOG_EN BIT(2)
#define LTC4281_ADC_CTRL_METER_HALT BIT(5)
#define LTC4281_ADC_CTRL_METER_RESET BIT(6)
#define LTC4281_ADC_CTRL_REBOOT BIT(7)

#define LTC4281_REG_STATUS_LSB 0x1E
#define LTC4281_STATUS_OV BIT(0)
#define LTC4281_STATUS_UV BIT(1)
#define LTC4281_STATUS_OC_COOLDOWN BIT(2)
#define LTC4281_STATUS_POWER_GOOD BIT(3)
#define LTC4281_STATUS_ON_PIN BIT(4)
#define LTC4281_STATUS_FET_SHORT BIT(5)
#define LTC4281_STATUS_FET_BAD_COOLDOWN BIT(6)
#define LTC4281_STATUS_ON BIT(7)

#define LTC4281_REG_STATUS_MSB 0x1F /* read-only */

/* ---------- Measurements: 16-bit, MSB first (0x34-0x4B) ---------- */
#define LTC4281_REG_VGPIO 0x34
#define LTC4281_REG_VGPIO_MIN 0x36
#define LTC4281_REG_VGPIO_MAX 0x38
#define LTC4281_REG_VSOURCE 0x3A
#define LTC4281_REG_VSOURCE_MIN 0x3C
#define LTC4281_REG_VSOURCE_MAX 0x3E
#define LTC4281_REG_VSENSE 0x40
#define LTC4281_REG_VSENSE_MIN 0x42
#define LTC4281_REG_VSENSE_MAX 0x44
#define LTC4281_REG_POWER 0x46
#define LTC4281_REG_POWER_MIN 0x48
#define LTC4281_REG_POWER_MAX 0x4A
#define LTC4281_MEAS_LEN 2

/* ---------- Scaling constants ---------- */
#define LTC4281_VSENSE_FS_UV 40000U /* 40 mV current-sense full scale */
#define LTC4281_VGPIO_FS_MV 1280U
#define LTC4281_ADC_MAX_16BIT 65535U

#define LTC4281_VFS_3V3_MV 5547U
#define LTC4281_VFS_5V_MV 8320U
#define LTC4281_VFS_12V_MV 16640U
#define LTC4281_VFS_24V_MV 33280U

#endif /* LTC4281_REGS_H_ */